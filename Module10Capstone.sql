  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'AZURE'
  ENABLED = TRUE
  AZURE_TENANT_ID = 'befd7f93-cf9d-450f-aeb9-b71889f63327'
  STORAGE_ALLOWED_LOCATIONS = ('azure://jdobbinsutaustin.blob.core.windows.net/project-raw/');

GRANT USAGE ON INTEGRATION JD57922_STORAGE_INTEGRATION TO ROLE CHEETAH_ROLE;

USE ROLE CHEETAH_ROLE;
USE WAREHOUSE CHEETAH_WH;
USE DATABASE CHEETAH_DB;

CREATE SCHEMA IF NOT EXISTS RAW_BUSINESS_DATA;
USE SCHEMA RAW_BUSINESS_DATA;

CREATE OR REPLACE FILE FORMAT RAW_BUSINESS_DATA.RAW_CSV_FORMAT
  TYPE = 'CSV'
  FIELD_DELIMITER = ','
  SKIP_HEADER = 0
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  ESCAPE_UNENCLOSED_FIELD = NONE
  EMPTY_FIELD_AS_NULL = FALSE
  ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;


CREATE OR REPLACE STAGE RAW_BUSINESS_DATA.RAW_AZURE_STAGE
  STORAGE_INTEGRATION = JD57922_STORAGE_INTEGRATION
  URL = 'azure://jdobbinsutaustin.blob.core.windows.net/project-raw/'
  FILE_FORMAT = RAW_BUSINESS_DATA.RAW_CSV_FORMAT;

LIST @RAW_BUSINESS_DATA.RAW_AZURE_STAGE;


CREATE OR REPLACE TRANSIENT TABLE RAW_BUSINESS_DATA.RAW_BUSINESS_DATA (
  RAW_ROW       VARCHAR,
  SOURCE_FILE   VARCHAR,
  LOAD_TS       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TRANSIENT TABLE RAW_BUSINESS_DATA.RAW_STORE_DETAILS (
  RAW_ROW       VARCHAR,
  SOURCE_FILE   VARCHAR,
  LOAD_TS       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


COPY INTO RAW_BUSINESS_DATA.RAW_BUSINESS_DATA (RAW_ROW, SOURCE_FILE)
  FROM (
    SELECT $1, METADATA$FILENAME
